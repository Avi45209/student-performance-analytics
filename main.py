import pandas as pd
import numpy as np
from google.colab import files
import io

# Upload the student CSV file
uploaded = files.upload()

# Read the uploaded file, whatever its name
filename = next(iter(uploaded))
students = pd.read_csv(io.BytesIO(uploaded[filename]))

print("Dataset loaded successfully!")
print(students.head())
print("Total students:", len(students))

# Calculate student performance

subjects = [
    "Python_Marks",
    "Mathematics_Marks",
    "AI_Marks"
]

# Calculate total and average marks using NumPy
marks = students[subjects].to_numpy()

students["Total_Marks"] = np.sum(marks, axis=1)
students["Average_Marks"] = np.round(
    np.mean(marks, axis=1), 2
)

# Function to assign grades
def assign_grade(avg):
    if avg >= 90:
        return "A"
    elif avg >= 75:
        return "B"
    elif avg >= 60:
        return "C"
    elif avg >= 40:
        return "D"
    else:
        return "F"

# Function to check pass or fail
def check_result(row):
    for subject in subjects:
        if row[subject] < 35:
            return "Fail"
    return "Pass"

# Apply the functions
students["Grade"] = students["Average_Marks"].apply(assign_grade)
students["Result"] = students.apply(check_result, axis=1)

# Display student results
print("STUDENT PERFORMANCE RESULTS")
display(students[
    ["Student_ID", "Name", "Total_Marks",
     "Average_Marks", "Grade", "Result"]
])

# Class summary
print("\nCLASS SUMMARY")
print("Total students:", len(students))
print("Class average:", round(students["Average_Marks"].mean(), 2))
print("Highest average:", students["Average_Marks"].max())
print("Lowest average:", students["Average_Marks"].min())
print("Students passed:", (students["Result"] == "Pass").sum())
print("Students failed:", (students["Result"] == "Fail").sum())

# Subject-wise analysis
print("\nSUBJECT-WISE AVERAGES")
print(students[subjects].mean().round(2))

# Top five performers
print("\nTOP 5 PERFORMERS")
display(students.nlargest(5, "Average_Marks")[
    ["Name", "Department", "Average_Marks", "Grade"]
])

# Save results
students.to_csv("student_results.csv", index=False)
print("Results saved successfully!")

